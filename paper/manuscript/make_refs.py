"""Write refs.bib for the manuscript from ../references.bib (the verified bibliography).

    python make_refs.py

The source bib keeps the verification notes (``file``, ``note``) and the issue
``number`` for article records. JQAS asks for author-year references WITHOUT
issue numbers, so this filter drops ``number``, ``file`` and ``note``, and
replaces them by one short ``note`` that carries the DOI (or the arXiv
identifier) so the reference list shows how to find each source. Only the
standard library is used. Entries and keys are unchanged.

Only entries cited in main.tex or sections/*.tex are written (the source bib
may hold more); a cited key missing from the source is an error. A source
field ``outnote`` replaces the generated note (used for software and web
services, which have neither a DOI nor an arXiv identifier).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "references.bib"
OUT = HERE / "refs.bib"

DROP = {"file", "note", "outnote", "number", "archiveprefix", "primaryclass", "month", "publisher", "url"}
#: Keys whose source record has neither a DOI nor an arXiv identifier.
NOTE_OVERRIDE = {"gelman2013garden": "Unpublished manuscript, Columbia University"}

ENTRY = re.compile(r"@(\w+)\s*\{\s*([^,\s]+)\s*,(.*?)\n\}\s*(?=\n|\Z)", re.S)
FIELD = re.compile(r"^\s*(\w+)\s*=\s*", re.M)


def parse_fields(body: str) -> dict[str, str]:
    """Split ``name = {value},`` pairs, honouring nested braces."""
    out: dict[str, str] = {}
    pos = 0
    while True:
        m = FIELD.search(body, pos)
        if not m:
            break
        i = m.end()
        if body[i] == "{":
            depth, j = 0, i
            while True:
                depth += (body[j] == "{") - (body[j] == "}")
                j += 1
                if depth == 0:
                    break
            val = body[i + 1 : j - 1]
        else:
            j = body.find(",", i)
            j = len(body) if j < 0 else j
            val = body[i:j].strip()
        out[m.group(1).lower()] = val
        pos = j
    return out


CITE = re.compile(r"\\cite[a-z]*\*?(?:\[[^\]]*\])*\{([^}]*)\}")


def cited_keys() -> set[str]:
    keys: set[str] = set()
    for path in [HERE / "main.tex", *sorted((HERE / "sections").glob("*.tex"))]:
        text = re.sub(r"(?<!\\)%.*$", "", path.read_text(encoding="utf-8"), flags=re.M)
        for group in CITE.findall(text):
            keys.update(k.strip() for k in group.split(",") if k.strip())
    return keys


def main() -> int:
    text = SRC.read_text(encoding="utf-8")
    text = re.sub(r"^%.*$", "", text, flags=re.M)
    wanted = cited_keys()
    entries = []
    seen: set[str] = set()
    for kind, key, body in ENTRY.findall(text + "\n"):
        if key not in wanted:
            continue
        seen.add(key)
        f = parse_fields(body)
        note = f.get("outnote") or NOTE_OVERRIDE.get(key)
        if note is None:
            if kind.lower() == "misc" and "eprint" in f:
                note = f"arXiv preprint arXiv:{f['eprint']}"
            elif "doi" in f:
                note = f"https://doi.org/{f['doi']}"
            elif "eprint" in f:
                note = f"arXiv:{f['eprint']}"
        kind = kind.lower()
        if kind == "misc":
            kind = "unpublished"  # apalike wants a note, and no journal, for a preprint
            f.pop("howpublished", None)
        keep = {k: v for k, v in f.items() if k not in DROP and k not in ("eprint", "doi")}
        if note:
            keep["note"] = note
        lines = [f"@{kind}{{{key},"] + [f"  {k} = {{{v}}}," for k, v in keep.items()] + ["}"]
        entries.append("\n".join(lines))
    if wanted - seen:
        raise SystemExit(f"cited but not in references.bib: {sorted(wanted - seen)}")
    if wanted - seen:
        raise SystemExit(f"cited but not in references.bib: {sorted(wanted - seen)}")
    OUT.write_text(
        "% GENERATED by make_refs.py from ../references.bib - do not edit.\n\n" + "\n\n".join(entries) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {OUT.name}: {len(entries)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
